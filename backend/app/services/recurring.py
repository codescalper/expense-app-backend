"""Recurring expenses & bills (spec §9): rules, the generation engine, payment status, reminders.

Rules
-----
A rule (``recurring_transactions``) is a transaction template plus a schedule (see
:mod:`app.services.recurrence`). ``next_due_date`` is the **generation cursor**: the earliest
scheduled date that has not been processed yet. Once the schedule is exhausted the cursor holds
the first scheduled date *after* ``end_date`` and the rule's status is ``ended``.

* Creating a rule sets the cursor to ``start_date`` — a start date in the past means the missed
  occurrences are generated (as *pending*) by catch-up.
* Changing the schedule (frequency / interval / start date) moves the cursor to the first new
  occurrence after the latest period already generated (and not before ``start_date``).
* Turning ``auto_generate`` on likewise never back-fills occurrences due before today.
* Pausing stops generation and reminders. Resuming does **not** back-fill occurrences that fell
  due while paused: the cursor jumps to the first occurrence on/after today (owner's time zone).
* Deleting soft-deletes the rule; already generated transactions are kept as they are.

Generation (``generate_due``, run by the worker every 15 minutes)
----------------------------------------------------------------
For every live, unpaused, ``auto_generate`` rule, each occurrence with due date ≤ today (in the
rule owner's ``users.timezone``) becomes **one pending transaction** (status ``pending``, source
``recurring``, verification ``unverified``, ``occurred_at`` = due date 09:00 local time) keyed by
``(recurring_id, period_key)``. Inserts use ``ON CONFLICT DO NOTHING`` on that unique key, so
re-runs, concurrent workers and API races can never create a second row for a period — not even
after the generated row was soft-deleted. At most 12 occurrences per rule are processed per run
(catch-up continues on the next run). Nothing is ever marked paid automatically.

Payment status: ``mark_paid`` (→ completed, ``user_confirmed``), ``skip`` (→ cancelled) and
``unmark`` (→ pending) — only on transactions generated by a rule the caller may edit.

Reminders (``send_reminders``): ``bill_upcoming`` from ``reminder_days_before`` days ahead of a due
date until the due date, while the occurrence is not paid/skipped; ``recurring_reminder`` once a
generated occurrence is still pending the day after its due date (looking back 7 days). Dedupe
keys ``recurring:<id>:<period_key>:upcoming|overdue`` make both idempotent. Recipients: the owner
of a personal rule; for a family rule its owner plus the family's owner and admins.
"""

