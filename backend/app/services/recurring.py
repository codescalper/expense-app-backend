@dataclass
class _FieldErrors:
    items: list[dict[str, str]]

    def add(self, field: str, message: str) -> None:
        self.items.append({"field": field, "message": message, "type": "value_error"})

    def raise_if_any(self) -> None:
        if self.items:
            raise ValidationFailedError(details=self.items)


