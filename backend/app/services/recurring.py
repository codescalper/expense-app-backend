class RecurringService:
    def __init__(self, session: AsyncSession) -> None:
        self.db = session
        self.repo = RecurringRepository(session)
        self.audit = AuditRepository(session)

    # ------------------------------------------------------------------ helpers

    def _audit(
        self,
        action: str,
        user: User,
        client: ClientInfo,
        *,
        entity_type: str,
        entity_id: uuid.UUID,
        family_id: uuid.UUID | None,
        **details: object,
    ) -> None:
        self.audit.record(
            action,
            actor_user_id=user.id,
            entity_type=entity_type,
            entity_id=entity_id,
            family_id=family_id,
            ip_address=client.ip,
            user_agent=client.user_agent,
            details=dict(details),
        )

    async def _scope_for(self, user: User, family_id: uuid.UUID | None) -> ScopeFilter:
        """``family_id`` absent → my personal rows; present → that family (404 if not a member)."""
        if family_id is None:
            return ScopeFilter.for_user(user.id, scope=RecordScope.PERSONAL)
        await require_family_access(self.db, user, family_id, FamilyPermission.VIEW)
        return ScopeFilter.for_user(user.id, family_id=family_id)

    async def _out(self, user: User, rule: RecurringTransaction) -> RecurringOut:
        latest = await self.repo.latest_occurrences([rule.id])
        roles = await list_user_family_roles(self.db, user.id)
        return rule_out(rule, latest.get(rule.id), can_edit=can_edit_rule(user.id, rule, roles))

    async def _check_references(
        self,
        user: User,
        family_id: uuid.UUID | None,
        values: dict[str, Any],
        fields: set[str] | frozenset[str],
    ) -> None:
        """Referenced account / category / payee must be visible and in the rule's scope;
        a category's kind must match the rule type. Newly referenced accounts must be active
        and newly referenced categories not archived (an existing reference that was archived
        later doesn't block unrelated edits)."""
        errors = _FieldErrors([])
        for field in ("account_id", "to_account_id"):
            ref = values.get(field)
            if (field in fields or "currency" in fields) and ref is not None:
                account = await self.repo.account_in_scope(ref, user.id, family_id)
                if account is None:
                    errors.add(field, "Account not found in this scope")
                elif field in fields and not account.is_active:
                    errors.add(field, "This account is archived")
                elif values.get("currency") and account.currency != values["currency"]:
                    errors.add(field, "The account's currency differs from the rule's currency")
        payee_id = values.get("payee_id")
        if (
            "payee_id" in fields
            and payee_id is not None
            and await self.repo.payee_in_scope(payee_id, user.id, family_id) is None
        ):
            errors.add("payee_id", "Payee not found in this scope")
        category_id = values.get("category_id")
        if ("category_id" in fields or "type" in fields) and category_id is not None:
            category = await self.repo.category_in_scope(category_id, user.id, family_id)
            if category is None:
                errors.add("category_id", "Category not found in this scope")
            else:
                expected = (
                    CategoryKind.INCOME
                    if values.get("type") == TransactionType.INCOME
                    else CategoryKind.EXPENSE
                )
                if category.kind is not expected:
                    errors.add("category_id", f"Category must be an {expected.value} category")
                elif "category_id" in fields and await self.repo.category_archived(category):
                    errors.add("category_id", "This category is archived")
        errors.raise_if_any()

    @staticmethod
    def _check_shape(rule: RecurringTransaction) -> None:
        """Cross-field rules on the merged rule (an update may change any subset)."""
        errors = _FieldErrors([])
        if rule.end_date is not None and rule.end_date < rule.start_date:
            errors.add("end_date", "end_date must not be before start_date")
        if rule.type == TransactionType.TRANSFER:
            if rule.account_id is None or rule.to_account_id is None:
                errors.add("to_account_id", "Transfers need both account_id and to_account_id")
            elif rule.account_id == rule.to_account_id:
                errors.add("to_account_id", "to_account_id must differ from account_id")
            if rule.category_id is not None:
                errors.add("category_id", "Transfers have no category")
        elif rule.to_account_id is not None:
            errors.add("to_account_id", "to_account_id is only allowed for transfers")
        errors.raise_if_any()

    async def _load_writable(self, user: User, rule_id: uuid.UUID) -> RecurringTransaction:
        rule = await self.repo.get(rule_id)
        await require_record_write(self.db, user.id, rule)
        if rule is None:  # pragma: no cover - require_record_write raised already
            raise NotFoundError()
        return rule

    async def _owner_today(self, rule: RecurringTransaction) -> date:
        return local_today(utcnow(), zone(await self.repo.owner_timezone(rule.owner_user_id)))

    # ------------------------------------------------------------------ rules CRUD

    async def create(self, user: User, data: RecurringCreate, client: ClientInfo) -> RecurringOut:
        family_id = data.family_id if data.scope is RecordScope.FAMILY else None
        currency = data.currency
        if family_id is not None:
            await require_family_access(self.db, user, family_id, FamilyPermission.CREATE_RECORDS)
        if currency is None and data.account_id is not None:
            # Like transactions: default to the account's currency.
            account = await self.repo.account_in_scope(data.account_id, user.id, family_id)
            currency = account.currency if account is not None else None
        if currency is None and family_id is not None:
            currency = await self.repo.family_currency(family_id)
        values = {**data.model_dump(), "currency": currency or "INR"}
        await self._check_references(user, family_id, values, REFERENCE_FIELDS)
        rule = RecurringTransaction(
            owner_user_id=user.id,
            scope=data.scope,
            family_id=family_id,
            name=data.name,
            type=TransactionType(data.type),
            amount=data.amount,
            currency=currency or "INR",
            account_id=data.account_id,
            to_account_id=data.to_account_id,
            category_id=data.category_id,
            payee_id=data.payee_id,
            description=data.description,
            payment_method=data.payment_method,
            frequency=data.frequency,
            interval_count=data.interval_count,
            start_date=data.start_date,
            end_date=data.end_date,
            next_due_date=data.start_date,
            reminder_days_before=data.reminder_days_before,
            auto_generate=data.auto_generate,
            is_paused=False,
        )
        self.repo.add(rule)
        await self.db.flush()
        self._audit(
            "recurring.created",
            user,
            client,
            entity_type="recurring_transaction",
            entity_id=rule.id,
            family_id=family_id,
            name=rule.name,
            amount=str(rule.amount),
        )
        await self.db.commit()
        await self.db.refresh(rule)
        return await self._out(user, rule)

    async def list_rules(
        self,
        user: User,
        family_id: uuid.UUID | None,
        page: PageParams,
        status: str | None = None,
    ) -> Page[RecurringOut]:
        scope = await self._scope_for(user, family_id)
        rows, total = await paginate(self.db, self.repo.list_stmt(scope, status=status), page)
        latest = await self.repo.latest_occurrences([r.id for r in rows])
        roles = await list_user_family_roles(self.db, user.id)
        return Page.build(
            [
                rule_out(r, latest.get(r.id), can_edit=can_edit_rule(user.id, r, roles))
                for r in rows
            ],
            total,
            page,
        )

    async def get_rule(self, user: User, rule_id: uuid.UUID) -> RecurringOut:
        rule = await self.repo.get_visible(user.id, rule_id)
        if rule is None:
            raise NotFoundError("Recurring rule not found")
        return await self._out(user, rule)

    async def update(
        self, user: User, rule_id: uuid.UUID, data: RecurringUpdate, client: ClientInfo
    ) -> RecurringOut:
        rule = await self._load_writable(user, rule_id)
        was_auto = rule.auto_generate
        changes = data.model_dump(exclude_unset=True)
        if "type" in changes:
            changes["type"] = TransactionType(changes["type"])
        for field, value in changes.items():
            setattr(rule, field, value)
        self._check_shape(rule)
        merged = {f: getattr(rule, f) for f in (*REFERENCE_FIELDS, "type", "currency")}
        await self._check_references(user, rule.family_id, merged, set(changes))
        if SCHEDULE_FIELDS & changes.keys():
            floor = rule.start_date
            latest = await self.repo.latest_period_key(rule.id)
            if latest is not None:
                with contextlib.suppress(ValueError):
                    floor = max(floor, parse_period_key(latest) + timedelta(days=1))
            rule.next_due_date = cursor_from(recurrence_of(rule), floor)
        if rule.auto_generate and not was_auto and rule_status(rule) == "active":
            # Turning generation on never back-fills bills that were due before today.
            today = await self._owner_today(rule)
            if rule.next_due_date < today:
                rule.next_due_date = cursor_from(recurrence_of(rule), today)
        self._audit(
            "recurring.updated",
            user,
            client,
            entity_type="recurring_transaction",
            entity_id=rule.id,
            family_id=rule.family_id,
            fields=sorted(changes),
        )
        await self.db.commit()
        await self.db.refresh(rule)
        return await self._out(user, rule)

    async def delete(self, user: User, rule_id: uuid.UUID, client: ClientInfo) -> None:
        rule = await self._load_writable(user, rule_id)
        rule.deleted_at = utcnow()
        self._audit(
            "recurring.deleted",
            user,
            client,
            entity_type="recurring_transaction",
            entity_id=rule.id,
            family_id=rule.family_id,
        )
        await self.db.commit()

    async def set_paused(
        self, user: User, rule_id: uuid.UUID, paused: bool, client: ClientInfo
    ) -> RecurringOut:
        rule = await self._load_writable(user, rule_id)
        if rule.is_paused != paused:
            rule.is_paused = paused
            if not paused:
                # Occurrences that fell due while paused are not back-filled.
                today = await self._owner_today(rule)
                if rule.next_due_date < today and rule_status(rule) == "active":
                    rule.next_due_date = cursor_from(recurrence_of(rule), today)
            self._audit(
                "recurring.paused" if paused else "recurring.resumed",
                user,
                client,
                entity_type="recurring_transaction",
                entity_id=rule.id,
                family_id=rule.family_id,
            )
            await self.db.commit()
            await self.db.refresh(rule)
        return await self._out(user, rule)

    # ------------------------------------------------------------------ occurrences

    async def list_occurrences(
        self, user: User, rule_id: uuid.UUID, page: PageParams
    ) -> Page[OccurrenceOut]:
        if await self.repo.get_visible(user.id, rule_id) is None:
            raise NotFoundError("Recurring rule not found")
        rows, total = await paginate(self.db, self.repo.occurrences_stmt(rule_id), page)
        return Page.build([occurrence_out(t) for t in rows], total, page)

    async def upcoming(
        self,
        user: User,
        family_id: uuid.UUID | None,
        days: int,
        *,
        include_overdue: bool = True,
        now: datetime | None = None,
    ) -> list[UpcomingOut]:
        """Occurrences due from today to today+``days`` (caller's time zone) across visible,
        unpaused rules — generated or not — plus (optionally) still-pending generated
        occurrences that are already overdue."""
        scope = await self._scope_for(user, family_id)
        today = local_today(now or utcnow(), zone(user.timezone))
        last = today + timedelta(days=days)
        rules = list(await self.repo.rules_for_scope(scope))
        by_id = {r.id: r for r in rules}
        ids = list(by_id)
        generated = await self.repo.occurrences_in_range(ids, period_key(today), period_key(last))

        def item(rule: RecurringTransaction, due: date, tx: Transaction | None) -> UpcomingOut:
            return UpcomingOut(
                recurring_id=rule.id,
                name=rule.name,
                scope=rule.scope,
                family_id=rule.family_id,
                type=tx.type if tx else rule.type,
                amount=tx.amount if tx else rule.amount,
                currency=tx.currency if tx else rule.currency,
                account_id=tx.account_id if tx else rule.account_id,
                category_id=tx.category_id if tx else rule.category_id,
                payee_id=tx.payee_id if tx else rule.payee_id,
                due_date=due,
                period_key=period_key(due),
                days_until_due=(due - today).days,
                is_overdue=due < today and (tx is None or tx.status is TransactionStatus.PENDING),
                status=tx.status.value if tx else "scheduled",
                transaction_id=tx.id if tx else None,
            )

        items: list[UpcomingOut] = []
        if include_overdue:
            for pending in await self.repo.pending_before(ids, period_key(today)):
                if pending.recurring_id in by_id:
                    rule = by_id[pending.recurring_id]
                    items.append(item(rule, occurrence_due_date(pending), pending))
        for rule in rules:
            if rule.is_paused:
                continue
            for due in recurrence_of(rule).between(today, last, limit=MAX_OCCURRENCES_PER_RULE):
                tx = generated.get((rule.id, period_key(due)))
                if tx is not None and tx.deleted_at is not None:
                    continue  # the user deleted this occurrence; it will never come back
                items.append(item(rule, due, tx))
        items.sort(key=lambda i: (i.due_date, i.name.lower(), str(i.recurring_id)))
        return items

    # ------------------------------------------------------------------ payment status

    async def _load_occurrence(self, user: User, transaction_id: uuid.UUID) -> Transaction:
        """A live transaction generated by a recurring rule the caller may edit (404/403)."""
        tx = await self.repo.get_generated_transaction(transaction_id)
        await require_record_write(self.db, user.id, tx)
        if tx is None:  # pragma: no cover - require_record_write raised already
            raise NotFoundError()
        return tx

    def _audit_status(
        self, action: str, user: User, client: ClientInfo, tx: Transaction, old: str
    ) -> None:
        self._audit(
            action,
            user,
            client,
            entity_type="transaction",
            entity_id=tx.id,
            family_id=tx.family_id,
            recurring_id=str(tx.recurring_id),
            period_key=tx.period_key,
            old_status=old,
            new_status=tx.status.value,
            amount=str(tx.amount),
        )

    async def mark_paid(
        self, user: User, transaction_id: uuid.UUID, data: MarkPaidRequest, client: ClientInfo
    ) -> OccurrenceOut:
        tx = await self._load_occurrence(user, transaction_id)
        if tx.status is TransactionStatus.FAILED:
            raise ConflictError("This occurrence cannot be marked as paid", code="invalid_status")
        if data.account_id is not None:
            errors = _FieldErrors([])
            # The occurrence's scope (its owner's personal accounts, or the family's).
            account = await self.repo.account_in_scope(
                data.account_id,
                tx.owner_user_id if tx.family_id is None else user.id,
                tx.family_id,
            )
            if account is None:
                errors.add("account_id", "Account not found in this scope")
            elif tx.type == TransactionType.TRANSFER and data.account_id == tx.to_account_id:
                errors.add("account_id", "account_id must differ from to_account_id")
            elif data.account_id != tx.account_id and not account.is_active:
                errors.add("account_id", "This account is archived")
            elif account.currency != tx.currency:
                errors.add("account_id", "The account's currency differs from the bill's")
            errors.raise_if_any()
            tx.account_id = data.account_id
        old = tx.status.value
        if data.amount is not None:
            tx.amount = data.amount
        if data.occurred_at is not None:
            tx.occurred_at = data.occurred_at
        if data.external_ref is not None:
            tx.external_ref = data.external_ref
        tx.status = TransactionStatus.COMPLETED
        tx.verification = VerificationStatus.USER_CONFIRMED
        self._audit_status("recurring.occurrence_paid", user, client, tx, old)
        await self.db.commit()
        await self.db.refresh(tx)
        return occurrence_out(tx)

    async def skip(
        self, user: User, transaction_id: uuid.UUID, client: ClientInfo
    ) -> OccurrenceOut:
        tx = await self._load_occurrence(user, transaction_id)
        if tx.status is not TransactionStatus.CANCELLED:
            if tx.status is not TransactionStatus.PENDING:
                raise ConflictError(
                    "Only an unpaid occurrence can be skipped (unmark the payment first)",
                    code="invalid_status",
                )
            old = tx.status.value
            tx.status = TransactionStatus.CANCELLED
            self._audit_status("recurring.occurrence_skipped", user, client, tx, old)
            await self.db.commit()
            await self.db.refresh(tx)
        return occurrence_out(tx)

    async def unmark(
        self, user: User, transaction_id: uuid.UUID, client: ClientInfo
    ) -> OccurrenceOut:
        tx = await self._load_occurrence(user, transaction_id)
        if tx.status is not TransactionStatus.PENDING:
            if tx.status is TransactionStatus.FAILED:
                raise ConflictError("This occurrence cannot be reopened", code="invalid_status")
            old = tx.status.value
            tx.status = TransactionStatus.PENDING
            tx.verification = VerificationStatus.UNVERIFIED
            self._audit_status("recurring.occurrence_reopened", user, client, tx, old)
            await self.db.commit()
            await self.db.refresh(tx)
        return occurrence_out(tx)

    # ------------------------------------------------------------------ generation engine

    @staticmethod
    async def generate_due(db: AsyncSession, now: datetime) -> int:
        """Generate every due occurrence (see module docstring). Commits per rule; one failing
        rule never blocks the others. Returns the number of transactions created."""
        repo = RecurringRepository(db)
        # Coarse prefilter: no time zone is more than 14h ahead of UTC.
        horizon = now.astimezone(UTC).date() + timedelta(days=1)
        rule_ids = await repo.due_rule_ids(horizon)
        await db.commit()
        created = 0
        for rule_id in rule_ids:
            try:
                created += await RecurringService._generate_for_rule(db, rule_id, now)
                await db.commit()
            except Exception:  # isolate failures per rule; retried on the next run
                await db.rollback()
                log.exception("recurring_generation_failed", recurring_id=str(rule_id))
        if created:
            log.info("recurring_generated", created=created)
        return created

    @staticmethod
    async def _generate_for_rule(db: AsyncSession, rule_id: uuid.UUID, now: datetime) -> int:
        repo = RecurringRepository(db)
        locked = await repo.lock_for_generation(rule_id)
        if locked is None:  # gone, paused, or another worker holds it right now
            return 0
        rule, tz_name = locked
        tz = zone(tz_name)
        today = local_today(now, tz)
        rec = recurrence_of(rule)
        if not rule.auto_generate:
            # Reminder-only rule: just keep the cursor at the next occurrence on/after today.
            if rule.next_due_date < today:
                rule.next_due_date = cursor_from(rec, today)
            return 0
        audit = AuditRepository(db)
        due = rule.next_due_date
        processed = created = 0
        while due <= today and rec.within_end(due) and processed < CATCH_UP_LIMIT:
            key = period_key(due)
            tx_id = await repo.insert_occurrence(
                {
                    "owner_user_id": rule.owner_user_id,
                    "family_id": rule.family_id,
                    "scope": rule.scope,
                    "type": rule.type,
                    "status": TransactionStatus.PENDING,
                    "source": TransactionSource.RECURRING,
                    "verification": VerificationStatus.UNVERIFIED,
                    "amount": rule.amount,
                    "currency": rule.currency,
                    "account_id": rule.account_id,
                    "to_account_id": rule.to_account_id,
                    "category_id": rule.category_id,
                    "payee_id": rule.payee_id,
                    "description": rule.description or rule.name,
                    "payment_method": rule.payment_method,
                    "occurred_at": due_datetime(due, tz),
                    "recurring_id": rule.id,
                    "period_key": key,
                }
            )
            if tx_id is not None:
                created += 1
                audit.record(
                    "recurring.occurrence_generated",
                    actor_user_id=None,
                    entity_type="transaction",
                    entity_id=tx_id,
                    family_id=rule.family_id,
                    details={"recurring_id": str(rule.id), "period_key": key},
                )
            processed += 1
            due = cursor_from(rec, due + timedelta(days=1))
        if processed:
            rule.next_due_date = due
            rule.last_generated_at = now
        return created

    # ------------------------------------------------------------------ reminders

    @staticmethod
    async def send_reminders(db: AsyncSession, now: datetime) -> int:
        """Create due ``bill_upcoming`` / ``recurring_reminder`` notifications (idempotent via
        dedupe keys). Returns the number of notifications created."""
        repo = RecurringRepository(db)
        created = 0
        recipients: dict[uuid.UUID, list[uuid.UUID]] = {}

        async def recipients_of(rule: RecurringTransaction) -> list[uuid.UUID]:
            if rule.id not in recipients:
                recipients[rule.id] = await repo.reminder_recipients(rule)
            return recipients[rule.id]

        # -- upcoming: from reminder_days_before ahead of the due date until the due date
        plan: list[tuple[RecurringTransaction, date, list[date]]] = []
        for rule, tz_name in await repo.reminder_rules():
            today = local_today(now, zone(tz_name))
            window_end = today + timedelta(days=rule.reminder_days_before)
            dues = recurrence_of(rule).between(today, window_end, limit=MAX_OCCURRENCES_PER_RULE)
            if dues:
                plan.append((rule, today, dues))
        if plan:
            first = min(d[0] for _r, _t, d in plan)
            last = max(d[-1] for _r, _t, d in plan)
            existing = await repo.occurrences_in_range(
                [r.id for r, _t, _d in plan], period_key(first), period_key(last)
            )
            for rule, today, dues in plan:
                for due in dues:
                    key = period_key(due)
                    tx = existing.get((rule.id, key))
                    if tx is not None and (
                        tx.deleted_at is not None or tx.status is not TransactionStatus.PENDING
                    ):
                        continue  # already paid / skipped / deleted
                    verb = "Income expected" if rule.type == TransactionType.INCOME else "Due"
                    body = f"{verb} {_when(due, today)}: {_money(rule.amount, rule.currency)}"
                    for user_id in await recipients_of(rule):
                        if await notify(
                            db,
                            user_id=user_id,
                            category=NotificationCategory.BILL_UPCOMING,
                            title=f"Upcoming: {rule.name}",
                            body=body,
                            dedupe_key=f"recurring:{rule.id}:{key}:upcoming",
                            data={
                                "recurring_id": str(rule.id),
                                "period_key": key,
                                "due_date": due.isoformat(),
                                "transaction_id": str(tx.id) if tx else None,
                            },
                            family_id=rule.family_id,
                        ):
                            created += 1
                await db.commit()

        # -- overdue: generated occurrences still pending the day after their due date
        utc_today = now.astimezone(UTC).date()
        candidates = await repo.overdue_candidates(
            period_key(utc_today - timedelta(days=OVERDUE_LOOKBACK_DAYS + 1)),
            period_key(utc_today + timedelta(days=1)),
        )
        for tx, rule, tz_name in candidates:
            today = local_today(now, zone(tz_name))
            due = occurrence_due_date(tx)
            if not today - timedelta(days=OVERDUE_LOOKBACK_DAYS) <= due < today:
                continue
            key = tx.period_key or period_key(due)
            for user_id in await recipients_of(rule):
                if await notify(
                    db,
                    user_id=user_id,
                    category=NotificationCategory.RECURRING_REMINDER,
                    title=f"Not marked as paid: {rule.name}",
                    body=(
                        f"{_money(tx.amount, tx.currency)} was due on {due:%d %b %Y}. "
                        "Mark it as paid or skip it."
                    ),
                    dedupe_key=f"recurring:{rule.id}:{key}:overdue",
                    data={
                        "recurring_id": str(rule.id),
                        "period_key": key,
                        "due_date": due.isoformat(),
                        "transaction_id": str(tx.id),
                    },
                    family_id=rule.family_id,
                ):
                    created += 1
        await db.commit()
        return created
